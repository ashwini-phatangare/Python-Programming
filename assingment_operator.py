#ASSIGNMENT OPERATOR
#Assignment operators update the variable after every operation.
a = 10
b = 5
# assignment operators:are the operators used to assign values to variables .

a += b  # a = a + b
print("Addition Assignment :",a)  # Addition Assignment
a -= b # a = a -b 
print(" Subtraction Assignment :",a) # subtraction Assignment
a *= b # a =  a* b
print(" Multiplication  Assignment :",a) # multiplication  Assignment
a /= b #a =  a/b
print(" Division  Assignment :",a) # Division Assignment
a //= b # floor division
print(" floor division Assignment :",a) # floor division Assignment
a %= b #a =  a % b 
print(" Modulus  Assignment :",a) # Modulus  Assignment
a **= b # a = a ** b
print("  Exponential Assignment :",a) #  Exponential Assignment
